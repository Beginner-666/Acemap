"""Export a pooled candidate list for human qrels annotation.

This is a review helper, not part of the retrieval pipeline.  It never writes
qrels and never invents grades; the reviewer assigns grades against the fixed
query text and writes ``config/qrels.json``.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src import evaluation, jsonio, verification  # noqa: E402
from src.paper_features import paper_features  # noqa: E402
from src.text import normalize  # noqa: E402


def _parse_results(values):
    parsed = {}
    for value in values:
        if "=" not in value:
            raise ValueError("--results must use NAME=PATH")
        name, path = value.split("=", 1)
        parsed[name] = Path(path)
    if not parsed:
        raise ValueError("At least one --results NAME=PATH is required")
    return parsed


def _load(name, path):
    document = jsonio.read_json(path)
    version = document.get("schema_version")
    if version == 2:
        verification.validate_v2_document(document)
    elif version == 3:
        verification.validate_v3_document(document)
        if name in evaluation.DEFAULT_RESULTS and document["settings"]["ranker"] != name:
            raise ValueError(f"{path} was generated by {document['settings']['ranker']}")
    else:
        raise ValueError(f"{path} is not a v2 or v3 result document")
    return document


def _candidate(result, ranks, scores):
    features = paper_features(result["paper"])
    return {
        "key": result["key"],
        "title": features["title"],
        "year": features["year"],
        "doi": features["doi"],
        "abstract": features["abstract"][:600],
        "keywords": features["keywords"],
        "concepts": [item["display_name"] for item in features["concepts"]],
        "ranks": ranks,
        "scores": scores,
    }


def build_report(queries, documents, top):
    report = []
    for query in queries:
        text = normalize(query["text"])
        candidates = {}
        for name, document in documents.items():
            rows = {row["query"]: row for row in document["searches"]}
            row = rows.get(text)
            if row is None:
                raise ValueError(f"{name} does not contain query {text}")
            for rank, result in enumerate(row["results"][:top], 1):
                key = result["key"]
                entry = candidates.setdefault(key, {"result": result, "ranks": {},
                                                    "scores": {}})
                entry["ranks"][name] = rank
                entry["scores"][name] = result.get(
                    "score", result.get("fusion_score", 0.0))
        ordered = sorted(
            candidates.values(),
            key=lambda item: (min(item["ranks"].values()), item["result"]["key"]))
        report.append({
            "id": query["id"],
            "text": query["text"],
            "topic": query["topic"],
            "time_filter": query["time_filter"],
            "task": query["task"],
            "candidates": [_candidate(item["result"], item["ranks"], item["scores"])
                           for item in ordered],
        })
    return {"queries": report}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--queries", type=Path,
                        default=ROOT / "config" / "evaluation_queries.json")
    parser.add_argument("--results", action="append", required=True,
                        metavar="NAME=PATH")
    parser.add_argument("--top", type=int, default=10)
    parser.add_argument("--output", type=Path,
                        default=ROOT / "results" / "evaluation_candidates.json")
    args = parser.parse_args(argv)
    if args.top < 1:
        parser.error("--top must be >= 1")
    queries = evaluation.load_queries(args.queries)
    documents = {name: _load(name, path)
                 for name, path in _parse_results(args.results).items()}
    report = build_report(queries, documents, args.top)
    jsonio.write_json(args.output, report)
    print(f"Candidates: {args.output}; queries={len(queries)}; "
          f"pairs={sum(len(item['candidates']) for item in report['queries'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
